#!/usr/bin/env python3
"""Extract the pipe DMC programs (dmc_id 1-4, generic stepping) of linux-firmware i915/adlp_dmc.bin into a C++
header, like Linux intel_dmc.c parse_dmc_fw_package / parse_dmc_fw_header (DMC header v3).
Usage: gen_dmc_adlp_pipes.py adlp_dmc.bin WhateverXe/kern_wex_dmc_adlp_pipes.hpp"""
import hashlib,struct,sys
src,dst=sys.argv[1],sys.argv[2]
b=open(src,'rb').read()
module_type,header_len=struct.unpack('<II',b[:8])
assert module_type==9 and header_len*4==128,'CSS header'
o=128;plen,pver=b[o],b[o+1];n=struct.unpack('<I',b[o+12:o+16])[0]
assert pver==2 and plen*4==16+32*12 and n<=32,'package header'
pipes={}
for i in range(n):
    e=b[o+16+i*12:o+28+i*12]
    if 1<=e[1]<=4 and e[2:4]==b'**':pipes[e[1]]=struct.unpack('<I',e[4:8])[0]
assert sorted(pipes)==[1,2,3,4],'pipe DMC entries'
out=['// Generated by tools/gen_dmc_adlp_pipes.py from linux-firmware i915/adlp_dmc.bin',
 '// sha256 %s: pipe DMC programs A-D (generic stepping).'%hashlib.sha256(b).hexdigest(),
 '// Intel firmware license (linux-firmware LICENSE.i915): redistribution in binary form permitted.',
 '#pragma once','#include <stdint.h>','namespace WEXDMCADLPPipes {',
 'struct Program { uint32_t id,fwVersion,start,words,count; const uint32_t *mmioAddr,*mmioData,*payload; };']
progs=[]
for dmc_id in (1,2,3,4):
    p=o+plen*4+pipes[dmc_id]*4
    sig,hlen,hver,dmcc,proj,fwsize,fwver=struct.unpack('<IBBHIII',b[p:p+20])
    assert sig==0x40403E3E and hver==3 and hlen*4==256,'DMC header v3'
    start=struct.unpack('<I',b[p+20:p+24])[0];count=struct.unpack('<I',b[p+92:p+96])[0]
    addrs=struct.unpack('<20I',b[p+96:p+176])[:count];datas=struct.unpack('<20I',b[p+176:p+256])[:count]
    base=0x5F000+0x400*(dmc_id-1)
    assert count<=20 and all(base<=a<base+0x400 for a in addrs),'pipe DMC MMIO range'
    assert fwsize*4<=0x8000 and 0x50000<=start<0xA0000,'pipe DMC program range'
    payload=struct.unpack('<%dI'%fwsize,b[p+256:p+256+fwsize*4])
    out.append('static const uint32_t addr%d[%d]={%s};'%(dmc_id,count,','.join('0x%x'%a for a in addrs)))
    out.append('static const uint32_t data%d[%d]={%s};'%(dmc_id,count,','.join('0x%x'%d for d in datas)))
    out.append('static const uint32_t payload%d[%d]={'%(dmc_id,fwsize))
    for i in range(0,fwsize,8):out.append(' '+','.join('0x%08x'%w for w in payload[i:i+8])+',')
    out.append('};')
    progs.append('{%d,0x%x,0x%x,%d,%d,addr%d,data%d,payload%d}'%(dmc_id,fwver,start,fwsize,count,dmc_id,dmc_id,dmc_id))
    print('pipe DMC %d: fw 0x%x, start 0x%x, %d words, %d mmio'%(dmc_id,fwver,start,fwsize,count))
out.append('static const Program programs[4]={%s};'%','.join(progs))
out+=['}','']
open(dst,'w').write('\n'.join(out))
