#!/usr/bin/env python3
"""Extract the main DMC program of linux-firmware i915/adlp_dmc.bin into a C++ header.
Parsing follows Linux intel_dmc.c (CSS header, package header v2, DMC header v3).
Usage: gen_dmc_adlp.py adlp_dmc.bin WhateverXe/kern_wex_dmc_adlp.hpp"""
import hashlib,struct,sys
src,dst=sys.argv[1],sys.argv[2]
b=open(src,'rb').read()
module_type,header_len=struct.unpack('<II',b[:8]);version=struct.unpack('<I',b[88:92])[0]
assert module_type==9 and header_len*4==128,'CSS header'
o=128;plen,pver=b[o],b[o+1];n=struct.unpack('<I',b[o+12:o+16])[0]
assert pver==2 and plen*4==16+32*12 and n<=32,'package header'
main=None
for i in range(n):
    e=b[o+16+i*12:o+28+i*12]
    if e[1]==0 and e[2:4]==b'**':main=struct.unpack('<I',e[4:8])[0]
assert main is not None,'no generic main DMC entry'
p=o+plen*4+main*4
sig,hlen,hver,dmcc,proj,fwsize,fwver=struct.unpack('<IBBHIII',b[p:p+20])
assert sig==0x40403E3E and hver==3 and hlen*4==256,'DMC header v3'
start=struct.unpack('<I',b[p+20:p+24])[0];count=struct.unpack('<I',b[p+92:p+96])[0]
addrs=struct.unpack('<20I',b[p+96:p+176])[:count];datas=struct.unpack('<20I',b[p+176:p+256])[:count]
assert start==0x80000 and count<=20 and all(0x8F000<=a<=0x8FFFF for a in addrs),'main MMIO range'
payload=struct.unpack('<%dI'%fwsize,b[p+256:p+256+fwsize*4])
assert fwsize*4<=0x20000
out=['// Generated by tools/gen_dmc_adlp.py from linux-firmware i915/adlp_dmc.bin',
 '// sha256 %s, CSS version 0x%x, main DMC fw_version 0x%x (generic stepping entry).'%(hashlib.sha256(b).hexdigest(),version,fwver),
 '// Intel firmware license (linux-firmware LICENSE.i915): redistribution in binary form permitted.',
 '#pragma once','#include <stdint.h>','namespace WEXDMCADLP {',
 'constexpr uint32_t cssVersion=0x%x,fwVersion=0x%x,start=0x%x,count=%d,words=%d;'%(version,fwver,start,count,fwsize),
 'static const uint32_t mmioAddr[%d]={%s};'%(count,','.join('0x%x'%a for a in addrs)),
 'static const uint32_t mmioData[%d]={%s};'%(count,','.join('0x%x'%d for d in datas)),
 'static const uint32_t payload[%d]={'%fwsize]
for i in range(0,fwsize,8):out.append(' '+','.join('0x%08x'%w for w in payload[i:i+8])+',')
out+=['};','}','']
open(dst,'w').write('\n'.join(out))
print('main DMC fw 0x%x, %d words, %d mmio'%(fwver,fwsize,count))
